"""Draw every figure type from one log folder and write out_dir/README.md.

    .venv/bin/python paper/scripts/figures/plot_all.py [log_dir] [out_dir]

The runtime/, lifetime/ and energy/ subfolders of out_dir are rebuilt from scratch; nothing else
in out_dir is touched. To draw one figure type only, run its own script (same arguments).
"""
import shutil
import sys
from collections import defaultdict
from pathlib import Path

import energy_cumulative
import lifetime_alive
import lifetime_fnd
import lifetime_fnd_lnd
import lifetime_fnd_vs_nodes
import lifetime_lnd
import runtime_by_round
import runtime_cumulative
import runtime_mean
import runtime_overview
import runtime_vs_nodes
from common import DEFAULT_LOG, DEFAULT_OUT, FIRST, INDEX, ROOT, SKIPPED, load_runs

LOG = DEFAULT_LOG   # <- đổi thư mục log ở đây (hoặc truyền làm tham số đầu tiên)
OUT = DEFAULT_OUT   # <- thư mục lưu hình
SCRIPTS = [runtime_mean, runtime_by_round, runtime_cumulative, runtime_vs_nodes, runtime_overview,
           lifetime_fnd, lifetime_lnd, lifetime_fnd_lnd, lifetime_alive, lifetime_fnd_vs_nodes,
           energy_cumulative]
SECTIONS = ("runtime", "lifetime", "energy")


def shown(path):
    """Log folder as written in the README: relative to the repository when it lies inside it."""
    path = Path(path).resolve()
    return path.relative_to(ROOT) if path.is_relative_to(ROOT) else path


def write_index(out, log, empty):
    lines = ["# Paper figures", "",
             f"Generated by `.venv/bin/python paper/scripts/figures/plot_all.py` from `{shown(log)}`. Do not edit by "
             "hand: the script rewrites this file and the figure folders. Each figure is a vector PDF (fonts "
             "embedded) plus a 600-DPI PNG. Single-panel figures are one IEEE column wide (3.5 in) and "
             "`runtime/runtime_overview` is the full text width (7.16 in).", "",
             "- One script per figure type in `paper/scripts/figures/` (see the folder name below).",
             "- Runtime figures use every run, because re-runs of a map differ in wall-clock time.",
             "- Lifetime and energy figures use one run per map, because re-runs repeat the same "
             "deterministic simulation.",
             f"- Runtime means cover the first {FIRST:,} rounds.",
             "- A hatched bar, a hollow marker or a leading ≥ marks a metric not reached before the end of "
             "the run. Its value is the last logged round (a lower bound).", ""]
    sections = defaultdict(list)
    for rel, data, cap in INDEX:
        sections[rel.split("/")[0]].append((rel, data, cap))
    for name in SECTIONS:
        lines += [f"## {name.capitalize()}", "", "| Figure | Data | Suggested caption |", "|---|---|---|"]
        lines += [f"| `{rel}` | {data} | {cap} |" for rel, data, cap in sections[name]]
        lines.append("")
    if empty or SKIPPED:
        lines += ["## Not drawn", ""]
        lines += [f"- `{rid}`: empty log (no feasible routing in round 1)" for rid in empty]
        lines += [f"- {s}" for s in SKIPPED]
    (out / "README.md").write_text("\n".join(lines) + "\n")


def main():
    log = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(LOG)
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(OUT)
    runs, empty = load_runs(log)
    for name in SECTIONS:
        if (out / name).exists():
            shutil.rmtree(out / name)
    for script in SCRIPTS:
        script.draw(runs, out)
    write_index(out, log, empty)
    print(f"{len(INDEX)} figures written to {out}; {len(empty)} empty runs, {len(SKIPPED)} skipped groups")


if __name__ == "__main__":
    main()
